
CREATE TABLE IF NOT EXISTS traffic_accidents (
    id VARCHAR(30) PRIMARY KEY,
    source VARCHAR(30),
    severity SMALLINT,
    start_time TIMESTAMP,
    end_time TIMESTAMP,
    start_lat DOUBLE PRECISION,
    start_lng DOUBLE PRECISION,
    end_lat DOUBLE PRECISION,
    end_lng DOUBLE PRECISION,
    distance_mi DOUBLE PRECISION,
    description TEXT,
    street TEXT,
    city VARCHAR(150),
    county VARCHAR(150),
    state VARCHAR(10),
    zipcode VARCHAR(20),
    country VARCHAR(10),
    timezone VARCHAR(50),
    airport_code VARCHAR(20),
    weather_timestamp TIMESTAMP,
    temperature_f DOUBLE PRECISION,
    wind_chill_f DOUBLE PRECISION,
    humidity_pct DOUBLE PRECISION,
    pressure_in DOUBLE PRECISION,
    visibility_mi DOUBLE PRECISION,
    wind_direction VARCHAR(30),
    wind_speed_mph DOUBLE PRECISION,
    precipitation_in DOUBLE PRECISION,
    weather_condition VARCHAR(100),
    amenity BOOLEAN,
    bump BOOLEAN,
    crossing BOOLEAN,
    give_way BOOLEAN,
    junction BOOLEAN,
    no_exit BOOLEAN,
    railway BOOLEAN,
    roundabout BOOLEAN,
    station BOOLEAN,
    stop BOOLEAN,
    traffic_calming BOOLEAN,
    traffic_signal BOOLEAN,
    turning_loop BOOLEAN,
    sunrise_sunset VARCHAR(20),
    civil_twilight VARCHAR(20),
    nautical_twilight VARCHAR(20),
    astronomical_twilight VARCHAR(20)
);
